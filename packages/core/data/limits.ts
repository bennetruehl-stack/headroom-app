export function limitsForYear(year: number): Limit[] {
  const firstDay = String(year) + '-01-01';
  const lastDay = String(year) + '-12-31';
  return limits.filter((limit) => limit.validFrom <= lastDay && limit.validTo >= firstDay);
}
